#include "write_capture.h"
#include <apio.h>
/* Add only unused resources. No GPIO mux/pad/clock/global reset writes. PIO1
 * and all three baseline PIO0 machines/words0..6 remain completely unchanged.
 * These are diagnostic input-only samplers, with no SET/OUT/MOV pin outputs.
 */
void sb_write_capture_program_init(bool enable) {
    APIO_ASM_CONTINUE();
    APIO_SET_BLOCK_FROM_VAR(0,WC_HIGH_START);APIO_SET_SM_VAR(3);APIO_WRAP_BOTTOM();
    const unsigned short high[]={
        APIO_MOV_ISR_PINS, APIO_MOV_OSR_ISR, APIO_NOP, APIO_OUT_X(4),
        APIO_JMP_X_NOT_Y(WC_HIGH_START),
        APIO_JMP_PIN(WC_HIGH_START+7),APIO_JMP(WC_HIGH_START+20),
        APIO_NOP,
        APIO_MOV_OSR_PINS,APIO_NOP,APIO_OUT_X(4),
        APIO_JMP_PIN(WC_HIGH_START+13),APIO_SET_X(0),
        APIO_JMP_X_NOT_Y(WC_HIGH_START+17),
        APIO_MOV_ISR_OSR,APIO_IN_Y(4),APIO_JMP(WC_HIGH_START+8),
        APIO_PUSH_BLOCK,APIO_MOV_ISR_X,APIO_PUSH_BLOCK,APIO_WAIT_IRQ_HIGH(7)
    };
    _Static_assert(sizeof high/sizeof high[0]==WC_HIGH_WORDS,"high layout");
    for(unsigned i=0;i<WC_HIGH_WORDS;++i){if(i==WC_HIGH_WORDS-1)APIO_WRAP_TOP();APIO_ADD_INSTR(high[i]);}
    APIO_SM_CLKDIV_SET(1,0);
    APIO_SM_EXECCTRL_SET(APIO_EXECCTRL_JMP_PIN(29));
    APIO_SM_SHIFTCTRL_SET(APIO_IN_COUNT(30)|APIO_IN_SHIFTDIR_L|APIO_OUT_SHIFTDIR_R);
    APIO_SM_PINCTRL_SET(APIO_IN_BASE(0));
    APIO_SM_EXEC_INSTR(APIO_SET_Y(5));APIO_SM_JMP_TO_START();
    APIO_END_BLOCK_FROM(WC_HIGH_START);

    APIO_SET_BLOCK_VAR(2);APIO_GPIOBASE_0();APIO_SET_SM_VAR(0);APIO_WRAP_BOTTOM();
    const unsigned short low[]={
        APIO_MOV_ISR_PINS,APIO_MOV_OSR_ISR,APIO_OUT_NULL(16),APIO_OUT_X(4),
        APIO_JMP_X_NOT_Y(0),APIO_PUSH_BLOCK,
        APIO_MOV_OSR_PINS,APIO_OUT_NULL(16),APIO_OUT_X(4),
        APIO_JMP_X_NOT_Y(11),APIO_JMP(6),
        APIO_MOV_ISR_X,APIO_PUSH_BLOCK,APIO_WAIT_IRQ_HIGH(7)
    };
    _Static_assert(sizeof low/sizeof low[0]==WC_LOW_WORDS,"low layout");
    for(unsigned i=0;i<WC_LOW_WORDS;++i){if(i==WC_LOW_WORDS-1)APIO_WRAP_TOP();APIO_ADD_INSTR(low[i]);}
    APIO_SM_CLKDIV_SET(1,0);APIO_SM_EXECCTRL_SET(0);
    APIO_SM_SHIFTCTRL_SET(APIO_IN_COUNT(30)|APIO_OUT_SHIFTDIR_R);APIO_SM_PINCTRL_SET(0);
    APIO_SM_EXEC_INSTR(APIO_SET_Y(5));APIO_SM_JMP_TO_START();

    APIO_SET_SM_VAR(1);APIO_START();APIO_WRAP_BOTTOM();
    APIO_ADD_INSTR(APIO_WAIT_IRQ_HIGH(2)); /*14 exactly-one pulse announced */
    APIO_ADD_INSTR(APIO_WAIT_GPIO_HIGH(19));
    APIO_ADD_INSTR(APIO_MOV_ISR_STATUS); /*16 CS ending history at WE end */
    APIO_ADD_INSTR(APIO_PUSH_BLOCK);
    APIO_ADD_INSTR(APIO_IRQ_SET(4));
    APIO_WRAP_TOP();APIO_ADD_INSTR(APIO_WAIT_IRQ_HIGH(7));
    APIO_SM_CLKDIV_SET(1,0);APIO_SM_EXECCTRL_SET(APIO_STATUS_SEL_IRQ|APIO_STATUS_N(3));
    APIO_SM_SHIFTCTRL_SET(0);APIO_SM_PINCTRL_SET(0);APIO_SM_JMP_TO_START();

    APIO_SET_SM_VAR(2);APIO_START();APIO_WRAP_BOTTOM();
    APIO_ADD_INSTR(APIO_WAIT_GPIO_LOW(17)); /*20 independent CS1 edge */
    APIO_ADD_INSTR(APIO_WAIT_GPIO_HIGH(17));
    APIO_WRAP_TOP();APIO_ADD_INSTR(APIO_IRQ_SET(3));
    APIO_SM_CLKDIV_SET(1,0);APIO_SM_EXECCTRL_SET(0);APIO_SM_SHIFTCTRL_SET(0);
    APIO_SM_PINCTRL_SET(0);APIO_SM_JMP_TO_START();

    APIO_SET_SM_VAR(3);APIO_START();APIO_WRAP_BOTTOM();
    APIO_ADD_INSTR(APIO_WAIT_PIN_LOW(0)); /*23 count WE only when CS1 active */
    APIO_ADD_INSTR(APIO_JMP_PIN(28));
    APIO_ADD_INSTR(APIO_JMP_X_DEC(26));
    APIO_ADD_INSTR(APIO_IRQ_SET(2));
    APIO_WRAP_TOP();APIO_ADD_INSTR(APIO_WAIT_PIN_HIGH(0));
    APIO_ADD_INSTR(APIO_MOV_OSR_PINS); /*28 permit WE-before-CS1 */
    APIO_ADD_INSTR(APIO_OUT_Y(1));
    APIO_ADD_INSTR(APIO_JMP_NOT_Y(24));
    APIO_ADD_INSTR(APIO_JMP(23));APIO_END();
    APIO_SM_CLKDIV_SET(1,0);APIO_SM_EXECCTRL_SET(APIO_EXECCTRL_JMP_PIN(17));
    APIO_SM_SHIFTCTRL_SET(APIO_IN_COUNT(30)|APIO_OUT_SHIFTDIR_R);
    APIO_SM_PINCTRL_SET(APIO_IN_BASE(19));APIO_SM_EXEC_INSTR(APIO_SET_X(0));APIO_SM_JMP_TO_START();
    APIO_END_BLOCK();
    /* APIO_ENABLE_SMS replaces, rather than ORs, the block mask. Retain all
     * three existing PIO0 guards when enabling the fourth input-only SM. The
     * firmware calls init(false) and SDK set_enabled on SM3 only. */
    if(enable){APIO_ENABLE_SMS(0,15);APIO_ENABLE_SMS(2,15);}
}
